import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import process from 'node:process'

interface MdnProperty {
  syntax: string
  initial: string | string[]
  inherited: boolean
}

const require = createRequire(import.meta.url)
const properties: Record<string, MdnProperty> = require('mdn-data/css/properties.json')
const syntaxes: Record<string, { syntax: string }> = require('mdn-data/css/syntaxes.json')
const l10n: Record<string, unknown> = require('mdn-data/l10n/css.json')
const mdnVersion: string = require('mdn-data/package.json').version

const OUTPUT = join(import.meta.dirname, '..', 'src', 'data', 'css-properties.generated.ts')

const byCodePoint = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0)
const names = Object.keys(properties).sort(byCodePoint)

function propertyOf(name: string): MdnProperty {
  const property = properties[name]
  if (property === undefined) throw new Error(`mdn-data has no property ${name}`)
  return property
}

const isShorthand = (name: string): boolean => Array.isArray(propertyOf(name).initial)

function longhandsOf(name: string): string[] {
  const { initial } = propertyOf(name)
  if (!Array.isArray(initial)) return [name]
  return initial.flatMap(longhandsOf)
}

// A property is unitless when its grammar accepts a bare <number> or <integer> outside any
// function, after following <type> and <'property'> references. A number written for such a
// property means something other than px (line-height: 1.5, flex: 1, z-index: 2), so px must
// not be appended. This covers React's unitless list for every property mdn-data knows.
const FUNCTION_REFERENCE = /<[^>]*\(\)>/g
const REFERENCE = /<('?)([a-z0-9-]+)'?(?:\s*\[[^\]]*\])?>/g
const acceptsNumberMemo = new Map<string, boolean>()

function withoutFunctionArguments(syntax: string): string {
  let depth = 0
  let out = ''
  for (const char of syntax.replace(FUNCTION_REFERENCE, '')) {
    if (char === '(') depth++
    else if (char === ')') depth--
    else if (depth === 0) out += char
  }
  return out
}

function acceptsBareNumber(syntax: string, visiting: Set<string>): boolean {
  for (const [, quote, name] of withoutFunctionArguments(syntax).matchAll(REFERENCE)) {
    if (name === undefined) continue
    if (!quote && (name === 'number' || name === 'integer')) return true
    const key = quote ? `'${name}'` : name
    if (visiting.has(key)) continue
    let accepts = acceptsNumberMemo.get(key)
    if (accepts === undefined) {
      const definition = quote ? properties[name]?.syntax : syntaxes[name]?.syntax
      if (definition === undefined) continue
      visiting.add(key)
      accepts = acceptsBareNumber(definition, visiting)
      visiting.delete(key)
      acceptsNumberMemo.set(key, accepts)
    }
    if (accepts) return true
  }
  return false
}

const inherited = names.filter((name) => propertyOf(name).inherited)

// mdn-data uses l10n keys ("dependsOnUserAgent") where there is no single CSS initial value.
const initialValues = names.flatMap((name): [string, string][] => {
  const { initial } = propertyOf(name)
  return typeof initial === 'string' && !(initial in l10n) ? [[name, initial]] : []
})

const shorthands = names
  .filter(isShorthand)
  .map((name): [string, string[]] => [name, [...new Set(longhandsOf(name))].sort(byCodePoint)])

const unitless = names.filter((name) => acceptsBareNumber(propertyOf(name).syntax, new Set()))

const q = (value: string): string => JSON.stringify(value)

function setLiteral(values: string[]): string {
  return `new Set([\n${values.map((value) => `  ${q(value)},\n`).join('')}])`
}

function mapLiteral(entries: [string, string][]): string {
  return `new Map([\n${entries.map(([key, value]) => `  [${q(key)}, ${q(value)}],\n`).join('')}])`
}

function listMapLiteral(entries: [string, string[]][]): string {
  const lines = entries.map(([key, list]) => `  [${q(key)}, [${list.map(q).join(', ')}]],\n`)
  return `new Map<string, readonly string[]>([\n${lines.join('')}])`
}

const output = `// Generated by scripts/gen-css-data.ts from mdn-data ${mdnVersion}. Do not edit; run \`pnpm gen\`.

/** Properties that inherit by default. */
export const inheritedProperties: ReadonlySet<string> = ${setLiteral(inherited)}

/** Initial value of every property that has a single CSS initial value. */
export const initialValues: ReadonlyMap<string, string> = ${mapLiteral(initialValues)}

/** Every shorthand mapped to the longhands it sets, nested shorthands expanded, sorted. */
export const shorthandLonghands: ReadonlyMap<string, readonly string[]> = ${listMapLiteral(shorthands)}

/** Properties whose grammar accepts a bare number, so a numeric input gets no px unit. */
export const unitlessProperties: ReadonlySet<string> = ${setLiteral(unitless)}
`

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUTPUT, 'utf8')
  } catch {}
  if (current !== output) {
    process.stderr.write('src/data/css-properties.generated.ts is stale. Run `pnpm gen`.\n')
    process.exitCode = 1
  }
} else {
  mkdirSync(dirname(OUTPUT), { recursive: true })
  writeFileSync(OUTPUT, output)
}
